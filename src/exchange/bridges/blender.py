"""Blender, headless: ``blender -b [template.blend] --factory-startup --python-exit-code 1
--python <wrapper> -- <arguments file>``.

The pipeline's script is a Python file with ``run(args)``, called inside Blender, which returns a
dict (JSON-safe). It is imported with its own folder on ``sys.path`` (so it can import its
neighbours) and gets the arguments the operation passed, plus ``args["workdir"]``, a folder to
write into::

    import bpy

    def run(args):
        bpy.ops.wm.read_factory_settings(use_empty=True)
        ...
        return {"files": [out]}

``--factory-startup`` keeps the user's Blender add-ons and preferences out of the job, so the
result does not depend on how their Blender is set up. A pipeline that needs an add-on enables
it in its script.
"""

from __future__ import annotations

from pathlib import Path

from exchange.bridges.base import Bridge, BridgeError

WRAPPER = '''# Generated by Exchange: runs one pipeline script inside Blender and records its result.
import importlib.util, json, sys, traceback
args_path = sys.argv[sys.argv.index("--") + 1]
job = json.load(open(args_path, encoding="utf-8"))
script = {script!r}
outcome = {{"ok": False}}
try:
    sys.path.insert(0, script.rsplit("/", 1)[0] if "/" in script else ".")
    spec = importlib.util.spec_from_file_location("exchange_pipeline_script", script)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    outcome = {{"ok": True, "result": module.run({{**job["args"], "workdir": job["workdir"]}})}}
except Exception as exc:
    traceback.print_exc()
    outcome = {{"ok": False, "error": f"{{type(exc).__name__}}: {{exc}}"}}
with open(job["result"], "w", encoding="utf-8") as f:
    json.dump(outcome, f)
sys.exit(0 if outcome["ok"] else 1)
'''


class BlenderBridge(Bridge):
    def run(self, script: Path, args: dict, *, template: Path | None = None, timeout: float = 3600) -> dict:
        """Run ``script``'s ``run(args)`` in Blender (opening ``template`` first, if given)."""
        script = Path(script).resolve()
        if not script.is_file():
            raise BridgeError(f"no Blender script {script}")
        if template is not None and not Path(template).is_file():
            raise BridgeError(f"no Blender template {template}")
        args_path, result_path = self._job_files(args)
        wrapper = self.workdir / "exchange_blender_job.py"
        wrapper.write_text(WRAPPER.format(script=script.as_posix()), encoding="utf-8")
        command = [str(self.executable), "-b"]
        if template is not None:
            command.append(str(Path(template).resolve()))
        command += ["--factory-startup", "--python-exit-code", "1", "--python", str(wrapper), "--", str(args_path)]
        self._log(f"Blender: {script.name}" + (f" with {Path(template).name}" if template else ""))
        code = self._run_process(command, timeout=timeout, log_name="blender.log")
        return self._read_result(result_path, "blender.log", code)
