"""Daz Studio: a separate instance runs a generated DazScript at launch.

``DAZStudio.exe -instanceName Exchange -noPrompt -noDefaultScene <wrapper.dsa>``

* **A separate instance** (``-instanceName Exchange``) leaves a Daz Studio the user has open alone.
* **Prompts:** ``-noPrompt`` keeps message boxes from waiting for an answer.
* **No window-less mode:** Daz Studio always opens its window, so a job shows one while it runs.

The pipeline's script is a DazScript file defining ``exchangeRun(args)``, which returns an object
(saved as JSON). The generated wrapper reads the arguments from a JSON file named in the wrapper
itself (no command-line script arguments needed), ``include``s the script, records its result or
error, then asks Daz Studio to exit::

    function exchangeRun(args) {
        // args.source, args.workdir, ... as the operation passed them
        return { files: [ ... ] };
    }

If Daz Studio does not exit by itself, the bridge closes it once the result is written.

**The instance's settings** live in their own registry key (``HKCU\\Software\\DAZ\\Studio4[Exchange]``).
Left to Daz's defaults it checks for updates at every start (and quits from the update dialog
before the job runs), and finds its own content directories. So before each launch the bridge
copies the update setting and the content, Poser, import and MDL directory lists from the user's
main instance (``Studio4``). The main instance's key is only read.

**Daz's own log** (``%APPDATA%\\DAZ 3D\\Studio4 [Exchange]\\log.txt``) says why a job failed; the
console output is mostly the content database starting. It is copied into the work folder after
each run, and errors quote it.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
import time
from pathlib import Path

from exchange.bridges.base import Bridge, BridgeError

INSTANCE = "Exchange"
FLAGS = ["-instanceName", INSTANCE, "-noPrompt", "-noDefaultScene"]

REGISTRY_KEY = r"Software\DAZ"  # under HKEY_CURRENT_USER; tests point it elsewhere
MAIN_INSTANCE = "Studio4"
SHARED_SETTINGS = re.compile(r"AutoUpdate|CloudDir|Num(Content|Poser|Import|MDL)Dirs|(Content|Poser|Import|MDL)Dir\d+")
DIRECTORY_LIST = re.compile(r"(Content|Poser|Import|MDL)Dir\d+")


def instance_folder() -> Path | None:
    """Where Daz Studio keeps the Exchange instance's log and layout."""
    appdata = os.environ.get("APPDATA")
    return Path(appdata) / "DAZ 3D" / f"{MAIN_INSTANCE} [{INSTANCE}]" if appdata else None


def sync_instance_settings() -> list[str]:
    """Copy the shared settings from the main instance's key into the Exchange instance's;
    returns the names copied. Directory entries the main instance no longer has are removed."""
    if sys.platform != "win32":
        return []
    import winreg

    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, rf"{REGISTRY_KEY}\{MAIN_INSTANCE}") as main:
            values, i = {}, 0
            while True:
                try:
                    name, value, kind = winreg.EnumValue(main, i)
                except OSError:
                    break
                if SHARED_SETTINGS.fullmatch(name):
                    values[name] = (value, kind)
                i += 1
    except OSError:
        return []  # no main instance: leave Daz's defaults
    with winreg.CreateKey(winreg.HKEY_CURRENT_USER, rf"{REGISTRY_KEY}\{MAIN_INSTANCE}[{INSTANCE}]") as target:
        stale, i = [], 0
        while True:
            try:
                name = winreg.EnumValue(target, i)[0]
            except OSError:
                break
            if DIRECTORY_LIST.fullmatch(name) and name not in values:
                stale.append(name)
            i += 1
        for name in stale:
            winreg.DeleteValue(target, name)
        for name, (value, kind) in values.items():
            winreg.SetValueEx(target, name, 0, kind, value)
    return sorted(values)

WRAPPER = """// Generated by Exchange: runs one pipeline script inside Daz Studio and records its result.
// The script is included at the top level: included inside a function, its top-level names are
// not visible to its own functions.
var exchangeIncludeError = null;
try {
    include(%(script)s);
} catch (error) {
    exchangeIncludeError = error;
}
(function () {
    var argsPath = %(args)s;
    var resultPath = %(result)s;
    function readText(path) {
        var file = new DzFile(path);
        if (!file.open(DzFile.ReadOnly)) { throw new Error("cannot read " + path); }
        var text = file.read();
        file.close();
        return text;
    }
    function writeText(path, text) {
        var file = new DzFile(path);
        file.open(DzFile.WriteOnly | DzFile.Truncate);
        file.write(text);
        file.close();
    }
    var outcome;
    try {
        if (exchangeIncludeError !== null) { throw exchangeIncludeError; }
        var job = JSON.parse(readText(argsPath));
        var args = job.args;
        args.workdir = job.workdir;
        outcome = { ok: true, result: exchangeRun(args) };
    } catch (error) {
        outcome = { ok: false, error: String(error) };
    }
    writeText(resultPath, JSON.stringify(outcome));
    if (typeof App.delayedExit === "function") { App.delayedExit(0); } else { MainWindow.close(); }
})();
"""


class DazBridge(Bridge):
    exit_grace = 15.0  # shutting down (plugins, Iray, content database) takes a few seconds

    def run(self, script: Path, args: dict, *, timeout: float = 3600) -> dict:
        """Run ``script``'s ``exchangeRun(args)`` in a separate Daz Studio instance."""
        script = Path(script).resolve()
        if not script.is_file():
            raise BridgeError(f"no DazScript {script}")
        args_path, result_path = self._job_files(args)
        wrapper = self.workdir / "exchange_daz_job.dsa"
        wrapper.write_text(WRAPPER % {"args": json.dumps(args_path.as_posix()), "result": json.dumps(result_path.as_posix()),
                                      "script": json.dumps(script.as_posix())}, encoding="utf-8")
        self._log(f"Daz Studio: {script.name}")
        if sync_instance_settings():
            self._log(f"copied the update setting and content directories from {MAIN_INSTANCE}")
        started = time.time()
        code = self._run_process([str(self.executable), *FLAGS, str(wrapper)], timeout=timeout, log_name="daz.log",
                                 done=result_path.is_file)
        return self._read_result(result_path, self._copy_daz_log(started) or "daz.log", code)

    def _copy_daz_log(self, started: float) -> str | None:
        """Copy Daz Studio's own log of this run into the work folder; returns its name there."""
        folder = instance_folder()
        log = folder / "log.txt" if folder else None
        try:
            if log is None or log.stat().st_mtime < started:
                return None
            shutil.copyfile(log, self.workdir / "daz_studio_log.txt")
        except OSError:
            return None
        return "daz_studio_log.txt"
