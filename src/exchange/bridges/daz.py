"""Daz Studio: a separate instance runs a generated DazScript at launch.

``DAZStudio.exe -instanceName Exchange -noPrompt -noDefaultScene <wrapper.dsa>``

* **A separate instance** (``-instanceName Exchange``) leaves a Daz Studio the user has open alone.
* **Prompts:** ``-noPrompt`` keeps message boxes from waiting for an answer.
* **No window-less mode:** Daz Studio always opens its window, so a job shows one while it runs.

The pipeline's script is a DazScript file defining ``exchangeRun(args)``, which returns an object
(saved as JSON). The generated wrapper reads the arguments from a JSON file named in the wrapper
itself (no command-line script arguments needed), ``include``s the script, records its result or
error, then asks Daz Studio to exit::

    function exchangeRun(args) {
        // args.source, args.workdir, ... as the operation passed them
        return { files: [ ... ] };
    }

If Daz Studio does not exit by itself, the bridge closes it once the result is written.
"""

from __future__ import annotations

import json
from pathlib import Path

from exchange.bridges.base import Bridge, BridgeError

FLAGS = ["-instanceName", "Exchange", "-noPrompt", "-noDefaultScene"]

WRAPPER = """// Generated by Exchange: runs one pipeline script inside Daz Studio and records its result.
(function () {
    var argsPath = %(args)s;
    var resultPath = %(result)s;
    function readText(path) {
        var file = new DzFile(path);
        if (!file.open(DzFile.ReadOnly)) { throw new Error("cannot read " + path); }
        var text = file.read();
        file.close();
        return text;
    }
    function writeText(path, text) {
        var file = new DzFile(path);
        file.open(DzFile.WriteOnly | DzFile.Truncate);
        file.write(text);
        file.close();
    }
    var outcome;
    try {
        var job = JSON.parse(readText(argsPath));
        include(%(script)s);
        var args = job.args;
        args.workdir = job.workdir;
        outcome = { ok: true, result: exchangeRun(args) };
    } catch (error) {
        outcome = { ok: false, error: String(error) };
    }
    writeText(resultPath, JSON.stringify(outcome));
    if (typeof App.delayedExit === "function") { App.delayedExit(0); } else { MainWindow.close(); }
})();
"""


class DazBridge(Bridge):
    def run(self, script: Path, args: dict, *, timeout: float = 3600) -> dict:
        """Run ``script``'s ``exchangeRun(args)`` in a separate Daz Studio instance."""
        script = Path(script).resolve()
        if not script.is_file():
            raise BridgeError(f"no DazScript {script}")
        args_path, result_path = self._job_files(args)
        wrapper = self.workdir / "exchange_daz_job.dsa"
        wrapper.write_text(WRAPPER % {"args": json.dumps(args_path.as_posix()), "result": json.dumps(result_path.as_posix()),
                                      "script": json.dumps(script.as_posix())}, encoding="utf-8")
        self._log(f"Daz Studio: {script.name}")
        code = self._run_process([str(self.executable), *FLAGS, str(wrapper)], timeout=timeout, log_name="daz.log",
                                 done=result_path.is_file)
        return self._read_result(result_path, "daz.log", code)
